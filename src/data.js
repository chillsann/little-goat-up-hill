/* 字卡词：只返回「已学字」组成的词；没有就退回单字 */
function wordsFor(c, learned) {
  const ok = w => [...w].every(ch => /[，。！？、…·\s\-—]/.test(ch) || learned.has(ch));
  const hit = WORD_POOL.filter(w => w.includes(c) && w.length >= 2 && ok(w));
  return hit.length ? hit.slice(0, 3) : [c];
}

function buildChars() {
  const out = {...HINTS_L1};
  ALL_CHARS.forEach(c => {
    if (out[c]) return;
    const e = EMOJI_HINT[c] || DEFAULT_EMO[c.charCodeAt(0) % DEFAULT_EMO.length];
    out[c] = {
      e,
      h: `「${c}」藏在词语里，点一点听听怎么读`,
      w: wordsFor(c, new Set(ALL_CHARS)),
      x: 0,
    };
  });
  return out;
}
