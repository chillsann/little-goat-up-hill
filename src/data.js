/* ---------------- 构建 1~6 级 ---------------- */
function buildLevels() {
  const seen = new Set(), levels = [];
  let prevCount = 0;
  for (let li = 0; li < 6; li++) {
    const want = OFFICIAL_TOTAL[li] - prevCount;
    let news;
    if (li === 0) news = BOOKS_L1.flatMap(b => b.chars).slice();
    else news = [...RAW_LEVELS[li]].filter(c => !seen.has(c));
    news = [...new Set(news)];
    // 用补齐字凑够官方新增字数
    for (const c of FILLER) {
      if (news.length >= want) break;
      if (!seen.has(c) && !news.includes(c)) news.push(c);
    }
    news.forEach(c => seen.add(c));
    const allowed = [...seen];
    prevCount = seen.size;

    let books;
    if (li === 0) books = BOOKS_L1;
    else {
      const per = Math.ceil(news.length / 10);
      books = Array.from({length: 10}, (_, i) => {
        const zone = ZONES[li][i];
        return {
          book: TITLES[li][i], zone, emo: EMOS[(i + li) % EMOS.length],
          color: BADGE_COLORS[(i + li) % BADGE_COLORS.length],
          villain: `迷雾怪把「${zone}」的汉字宝石藏起来啦！`,
          chars: news.slice(i * per, (i + 1) * per),
          story: STORIES[li][i],
          badge: zone + '小勇士',
        };
      });
    }
    levels.push({
      ...LEVEL_META[li], total: OFFICIAL_TOTAL[li], newCount: want,
      chars: news, allowed, books,
    });
  }
  return levels;
}
