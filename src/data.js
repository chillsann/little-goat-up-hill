/* 每个册子要玩的两种游戏（轮换保证不重复到腻） */
function gamesForBook(i) {
  const a = GAME_ORDER[i % GAME_ORDER.length];
  const b = GAME_ORDER[(i + 2) % GAME_ORDER.length];
  return i === 9 ? ['gem', 'match'] : [a, b === a ? 'gem' : b];
}

